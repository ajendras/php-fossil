"""PHP version fingerprinting utilities.

Pure functions that detect PHP versions from HTTP headers, response bodies,
phpinfo() output and error pages. Used by the AsyncScanner.
"""

import re
from typing import Dict, Optional


def detect_from_headers(headers: Dict[str, str]) -> Optional[str]:
    """Detect PHP version from response headers.

    Prioritises X-Powered-By then Server header. Returns None if
    no version string is found or headers are empty.

    Args:
        headers: HTTP response headers (case-insensitive lookup).

    Returns:
        Detected version string (e.g. '7.4.33') or None.
    """
    if not headers or not isinstance(headers, dict):
        return None

    powered_by = (
        headers.get("X-Powered-By")
        or headers.get("x-powered-by")
        or headers.get("Server")
        or headers.get("server")
        or ""
    )

    match = re.search(
        r"(?i)PHP[/\s]?(?P<version>\d+\.\d+(?:\.\d+)?)", powered_by
    )
    if match:
        return match.group("version")
    return None


def detect_from_body(body: str) -> Optional[str]:
    """Detect PHP version from response body text.

    Scans for common patterns found in phpinfo(), footer comments,
    meta tags and generated error pages.

    Args:
        body: Raw response body (HTML or text).

    Returns:
        Detected version string or None.
    """
    if not body or not isinstance(body, str):
        return None

    patterns = [
        r"(?i)PHP\s+Version\s*[:=]?\s*['\"]?([0-9.]+)",
        r"PHP Version</td>\s*<td[^>]*>([0-9.]+)",
        r"(?i)php(?:\s+version)?\s*[:=]\s*['\"]?([0-9.]+)",
        r"Powered by PHP ([0-9.]+)",
        r"php-?version[\"']?\s*[:=]\s*[\"']?([0-9.]+)",
        r"Generated by PHP (\d+\.\d+\.?\d*)",
    ]

    for pattern in patterns:
        match = re.search(pattern, body, re.IGNORECASE | re.DOTALL)
        if match:
            candidate = match.group(1).strip()
            if re.match(r"^\d+\.\d+(\.\d+)?$", candidate):
                return candidate
    return None


def detect_from_phpinfo(content: str) -> Optional[str]:
    """Extract exact PHP version from a phpinfo() page.

    Targets the standard phpinfo() HTML table and heading format.

    Args:
        content: Full text of a phpinfo() response.

    Returns:
        Version string or None.
    """
    if not content or not isinstance(content, str):
        return None

    patterns = [
        r"<h1[^>]*>PHP Version ([0-9.]+)",
        r"PHP Version </td><td class=\"v\">([0-9.]+)",
        r"PHP Version.*?([0-9]+\.[0-9]+\.[0-9]+)",
        r"phpinfo\(\).*?(\d+\.\d+\.\d+)",
    ]

    for pattern in patterns:
        match = re.search(pattern, content, re.IGNORECASE | re.DOTALL)
        if match:
            return match.group(1).strip()
    return None


def detect_from_error_page(content: str) -> Optional[str]:
    """Detect PHP version from error pages (often leaked in footer).

    Many PHP installations expose version on 404 or fatal error pages.

    Args:
        content: Body of an error response.

    Returns:
        Version string or None.
    """
    if not content or not isinstance(content, str):
        return None

    # Primary pattern: "PHP Version: X.Y.Z"
    match = re.search(
        r"(?i)PHP Version[:\s]+([0-9]+\.[0-9]+\.[0-9]+)", content
    )
    if match:
        return match.group(1)

    # Common pattern in default Apache/PHP error output: "PHP/7.3.12"
    match = re.search(
        r"PHP/([0-9]+\.[0-9]+\.[0-9]+)", content, re.IGNORECASE
    )
    if match:
        return match.group(1)

    # Additional pattern often seen in parse error messages:
    # "... (PHP 7.3.12)" – capture the version inside parentheses.
    match = re.search(
        r"\(PHP\s+([0-9]+\.[0-9]+\.[0-9]+)\)", content, re.IGNORECASE
    )
    if match:
        return match.group(1)

    return None


def detect_php_version(
    headers: Optional[Dict[str, str]] = None,
    body: str = "",
    phpinfo_content: str = "",
) -> Optional[str]:
    """Convenience combiner: tries headers, phpinfo, then body.

    Order reflects reliability of each source. Used by tests.
    """
    if headers:
        ver = detect_from_headers(headers)
        if ver:
            return ver
    if phpinfo_content:
        ver = detect_from_phpinfo(phpinfo_content)
        if ver:
            return ver
    if body:
        ver = detect_from_body(body)
        if ver:
            return ver
    return None


__all__ = [
    "detect_from_headers",
    "detect_from_body",
    "detect_from_phpinfo",
    "detect_from_error_page",
    "detect_php_version",
]
